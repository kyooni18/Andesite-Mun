#!/usr/bin/env node
// Generates the TypeScript types of the /v1 responses from the server's JSON Schemas.
//
//   node scripts/gen-types.mjs [path/to/Andesite/docs/schemas]
//
// Defaults to ../Andesite/docs/schemas (or $ANDESITE_SCHEMAS). The schemas are
// copied to src/api/schemas/json/ so the contract tests can validate against exactly
// what the types were generated from; CI regenerates both and fails on a diff.
import { mkdirSync, readdirSync, readFileSync, rmSync, writeFileSync, copyFileSync } from 'node:fs'
import { resolve } from 'node:path'
import { compile } from 'json-schema-to-typescript'

const root = resolve(import.meta.dirname, '..')
const source = resolve(process.argv[2] ?? process.env.ANDESITE_SCHEMAS ?? resolve(root, '../Andesite/docs/schemas'))
const jsonDir = resolve(root, 'src/api/schemas/json')
rmSync(jsonDir, { recursive: true, force: true })
mkdirSync(jsonDir, { recursive: true })

const files = readdirSync(source).filter(name => name.endsWith('.json')).sort()
let output = `// GENERATED by scripts/gen-types.mjs from Andesite's docs/schemas. Do not edit.\n`
for (const file of files) {
  copyFileSync(resolve(source, file), resolve(jsonDir, file))
  const schema = JSON.parse(readFileSync(resolve(source, file), 'utf8'))
  const ts = await compile(schema, schema.title ?? file, {
    cwd: source + '/',
    bannerComment: '',
    additionalProperties: false,
    style: { singleQuote: true, semi: false },
    declareExternallyReferenced: Boolean(schema.$defs),
  })
  output += `\n// ${file}\n${ts}`
}
writeFileSync(resolve(root, 'src/api/schemas/types.ts'), output)
console.log(`Generated ${files.length} schemas into src/api/schemas`)
